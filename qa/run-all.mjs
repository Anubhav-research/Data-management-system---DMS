// npm run qa:all - builds both websites, runs every QA suite against the running demo (npm run dev:all) and writes
// qa/REPORT.md. Each suite starts from a reset (npm run reset:all), so the demo data is reset at the end too.
import { execFileSync, spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { QA_DIR, env } from './lib.mjs'

const ROOT = path.join(QA_DIR, '..')
const SUITES = [
  ['smoke', 'Route smoke test, both websites, IS / TL / VP / President / Admin'],
  ['junkrules', 'Junk rules A1–A5 (Prospect DMS) and Junk from Unassigned (Investor DMS)'],
  ['journeys', 'Carried-over user journeys J1–J12 and product-owner checks, on the website each now belongs to'],
  ['responsive', 'Tablet and phone widths, both websites'],
  ['split', 'Split tests TS-01 … TS-23'],
]
const started = new Date()
const build = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build:all'], { cwd: ROOT, encoding: 'utf8', shell: true })
const buildOk = build.status === 0
console.log(`build:all ${buildOk ? 'OK' : 'FAILED'}`)
const out = []
for (const [name, about] of SUITES) {
  execFileSync(process.execPath, [path.join(ROOT, 'scripts', 'reset-all.mjs')], { stdio: 'ignore' })
  const t = Date.now()
  const r = spawnSync(process.execPath, [path.join(QA_DIR, `${name}.mjs`)], { cwd: QA_DIR, encoding: 'utf8', timeout: 20 * 60000 })
  let data = null
  try { data = JSON.parse(fs.readFileSync(path.join(QA_DIR, `results-${name}.json`), 'utf8')) } catch {}
  const results = data?.results || []
  const pass = results.filter((x) => x.ok).length
  out.push({ name, about, results, problems: data?.problems || [], pass, total: results.length, exit: r.status, secs: Math.round((Date.now() - t) / 1000) })
  console.log(`${name}: ${pass}/${results.length} passed${r.status ? ` (exit ${r.status})` : ''}`)
}
execFileSync(process.execPath, [path.join(ROOT, 'scripts', 'reset-all.mjs')], { stdio: 'ignore' })

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const lines = [
  '# QA report – DMS split demo', '',
  `Run ${started.toISOString().replace('T', ' ').slice(0, 16)} UTC on Prospect DMS :${env.PDMS_PORT} and Investor DMS :${env.IDMS_PORT}. Browser: ${process.env.BROWSER || 'edge'} (playwright-core, headless).`, '',
  `**Builds:** ${buildOk ? 'both websites build (vite build)' : 'BUILD FAILED – see npm run build:all'}`, '',
  '| Suite | What it covers | Passed | Console / page errors | Time |', '|---|---|---|---|---|',
  ...out.map((s) => `| ${s.name} | ${s.about} | ${s.pass} / ${s.total} | ${s.problems.length || 'none'} | ${s.secs} s |`), '',
  `**Total: ${out.reduce((a, s) => a + s.pass, 0)} / ${out.reduce((a, s) => a + s.total, 0)} checks passed.**`, '',
  'Network responses 409 (the deliberate two-admins conflict), 502 (the bridge deliberately stopped in TS-15) and 503 (a flow switched off) are expected and not counted as errors. Generated by `npm run qa:all` (qa/run-all.mjs). Screenshots are in qa/shots/ (not committed). The split tests are described in X08 format in docs/X08_split_tests.md.', '',
]
for (const s of out) {
  const failed = s.results.filter((x) => !x.ok)
  lines.push(`## ${s.name}`, '')
  if (s.name === 'split') {
    lines.push('| Test | Result | Detail |', '|---|---|---|', ...s.results.map((x) => `| ${x.id} | ${x.ok ? 'PASS' : '**FAIL**'} | ${esc(x.detail)} |`), '')
  } else if (failed.length) {
    lines.push('Failed:', '', ...failed.map((x) => `- ${esc(x.id)} – ${esc(x.detail)}`), '')
  } else lines.push(`All ${s.total} checks passed.`, '')
  if (s.problems.length) lines.push('Console / page errors:', '', ...s.problems.slice(0, 30).map((p) => `- ${esc(p)}`), '')
}
fs.writeFileSync(path.join(QA_DIR, 'REPORT.md'), lines.join('\n'))
console.log('qa/REPORT.md written')
process.exitCode = buildOk && out.every((s) => s.pass === s.total && s.total > 0) ? 0 : 1
